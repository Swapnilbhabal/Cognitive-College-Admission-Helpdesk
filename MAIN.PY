@app.route("/api/send-summary", methods=["POST"])
def send_summary():
    """
    Receives the email and conversation ID from the frontend when the call ends,
    fetches the summary from ElevenLabs, and sends it via email.
    """
    data = request.json
    user_email = data.get("email")
    conversation_id = data.get("conversation_id")
    
    if not user_email:
        return jsonify({"error": "No email provided"}), 400

    # Default summary text if we don't have a conversation_id or if fetching fails
    summary_text = "We enjoyed speaking with you regarding your admission enquiry. Based on our conversation, we have logged your details."
    
    # If the frontend passes a conversation_id, fetch the exact AI summary!
    if conversation_id:
        try:
            # ElevenLabs takes a few seconds to generate the summary after a call ends.
            # We add a small delay to ensure the summary is ready before fetching.
            time.sleep(3) 
            
            url = f"https://api.elevenlabs.io/v1/convai/conversations/{conversation_id}"
            headers = {"xi-api-key": ELEVENLABS_API_KEY}
            response = requests.get(url, headers=headers)
            
            if response.status_code == 200:
                conv_data = response.json()
                # Extract the summary generated by the AI
                fetched_summary = conv_data.get("analysis", {}).get("data_collection_results", {}).get("summary")
                
                if not fetched_summary:
                    # Fallback to general transcript summary if specific data collection missed it
                    fetched_summary = conv_data.get("analysis", {}).get("evaluation_criteria_results", {}).get("summary")
                
                if fetched_summary:
                    summary_text = fetched_summary
        except Exception as e:
            print(f"Error fetching summary from ElevenLabs: {e}")

    sender_email = os.environ.get("EMAIL_ADDRESS")
    sender_password = os.environ.get("EMAIL_PASSWORD")

    if not sender_email or not sender_password:
        print("WARNING: Email credentials not set in .env file.")
        return jsonify({"status": "error", "message": "Email skipped (no credentials configured)."})

    try:
        # Construct the email
        msg = MIMEMultipart()
        msg['From'] = sender_email
        msg['To'] = user_email
        msg['Subject'] = "VIT Admissions: Conversation Summary"

        body = f"""Dear Student,

Thank you for interacting with the Vidyalankar Institute of Technology (VIT) AI Admission Assistant.

Here is a summary of your details and our conversation today:
{summary_text}

Our admission team will review your profile and contact you soon to guide you through the next steps (CAP rounds or Institutional rounds).

Best Regards,
VIT Admissions Cell
"""
        msg.attach(MIMEText(body, 'plain'))

        # Connect to Gmail SMTP server
        server = smtplib.SMTP('smtp.gmail.com', 587)
        server.starttls()
        
        # Login and send the email
        server.login(sender_email, sender_password)
        text = msg.as_string()
        server.sendmail(sender_email, user_email, text)
        server.quit()
        
        return jsonify({"status": "success", "message": "Email sent successfully."})
        
    except Exception as e:
        print(f"Error sending email: {e}")
        return jsonify({"status": "error", "message": str(e)}), 500

